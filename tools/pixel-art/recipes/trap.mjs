// 함정 — 올가미 (M22-3차 W5b 3차 시안, 사용자 방향 확정: "밧줄 + 휘어진 나무")
//
// 폐기 이력: ①쇠덫·가시 구덩이 = 청회색 금속이 나무 마을에서 겉돌았다 ②나무 말뚝 덫 =
// "함정처럼 생기지 않았다" (말뚝 줄은 울타리로 읽힌다). 공통 진단은 **형태 인식**이었다 —
// 색이 아니라 실루엣이 함정이라고 말해야 한다.
//
// 올가미의 실루엣은 두 부분이 만든다: **휘어져 당겨진 어린나무**(장력 = 곧 튄다)와
// **땅에 놓인 밧줄 고리**(밟는 자리). 둘이 밧줄로 이어져 있으면 16px에서도 "덫"으로 읽힌다.
//
// 2프레임: 0 = 설치(나무가 휘어 있고 고리가 열림), 1 = 발동(나무가 튕겨 서고 고리가 조임).
// 발동 프레임은 소멸 직전이지만, 나중에 발동 연출이 붙으면 그 자리에 바로 쓰인다.

const W = 32, H = 16;
const K = {
  S: 'wood_shadow', d: 'wood_dark', m: 'wood_mid', l: 'wood_light',
  r: 'wood_hi',      // 밧줄 (밝은 삼 색)
  g: 'leaf_mid', G: 'leaf_hi', D: 'leaf_dark',
};

const grid = Array.from({ length: H }, () => Array(W).fill('.'));
const put = (x, y, ch) => { if (x >= 0 && x < W && y >= 0 && y < H) grid[y][x] = ch; };
/** 굵기 2의 줄기 — 안쪽은 밝게(l), 바깥은 그림자(S)로 원통감을 준다. */
const stem = (x, y) => { put(x, y, 'S'); put(x + 1, y, 'm'); };

// ── 프레임 0 (x 0..15) — 설치: 나무가 크게 휘어 당겨져 있다 ─────────────────────
// 곡선을 약하게 그렸더니 "지팡이"로 보였다 → 밑동부터 끝까지 큰 C 자로 휘게 다시 그린다.
for (let y = 15; y >= 10; y--) stem(12, y);                          // 밑동 (땅에 박힌 부분)
[[12, 9], [11, 8], [11, 7], [10, 6], [9, 5], [8, 4]].forEach(([x, y]) => stem(x, y)); // 휘는 목
[[7, 3], [6, 3], [5, 3], [4, 4]].forEach(([x, y]) => stem(x, y));    // 끝이 눌려 아래로 (장력)
// 잎 — 휘어진 끝에 뭉치로 (어린나무라는 표시)
[[3, 3, 'G'], [4, 2, 'g'], [5, 2, 'G'], [6, 2, 'g'], [7, 2, 'D'], [8, 3, 'g'], [3, 5, 'D']]
  .forEach(([x, y, c]) => put(x, y, c));
// 당김 밧줄 — 휜 끝에서 땅의 고리로 (팽팽하게 한 줄)
for (let y = 6; y <= 9; y++) put(4, y, 'r');
// 땅의 고리 — 넓은 타원으로 (밟는 자리가 보여야 덫이다)
[[3, 10], [4, 10], [5, 10], [6, 10], [7, 10],
 [2, 11], [8, 11], [1, 12], [9, 12], [1, 13], [9, 13],
 [2, 14], [3, 14], [4, 14], [5, 14], [6, 14], [7, 14], [8, 14]]
  .forEach(([x, y]) => put(x, y, 'r'));

// ── 프레임 1 (x 16..31) — 발동: 나무가 튕겨 서고 고리가 조였다 ────────────────
for (let y = 14; y >= 3; y--) stem(22, y);                 // 곧게 선 줄기
[[21, 2], [22, 1], [23, 2]].forEach(([x, y]) => put(x, y, 'g'));
[[22, 0]].forEach(([x, y]) => put(x, y, 'G'));
[[20, 3], [24, 3]].forEach(([x, y]) => put(x, y, 'D'));
// 팽팽해진 밧줄 — 위로 당겨 올라간다
for (let y = 5; y <= 11; y++) put(20, y, 'r');
// 조인 고리 (작아졌다)
[[19, 12], [20, 12], [21, 12], [19, 13], [21, 13], [20, 14]].forEach(([x, y]) => put(x, y, 'r'));

export default {
  name: 'Trap',
  width: W,
  height: H,
  slices: [
    { name: 'Trap_0', x: 0, y: 0, w: 16, h: 16 },
    { name: 'Trap_1', x: 16, y: 0, w: 16, h: 16 },
  ],
  layers: [{ op: 'pixels', at: [0, 0], key: K, map: grid.map(r => r.join('')) }],
};
