ATTACK_WIND = 0.34      # 주기 중 **뒤로 빼는**(예비) 구간 비율. 나머지가 치고 되돌아오는 시간


def attack(t):
    """맨손 타격 — Fight 가 쓴다(`AnimKind.Attack`). 주기 0.9 초.

    🔴 `chop` 과 같은 실수를 반복하지 마라. 대칭 곡선으로 적으면 「친다」가 아니라
       「팔을 내민다」가 된다. 셋으로 짓는다: **뒤로 뺐다가 → 가속해서 치고 → 되돌아온다.**
    🔑 **몸이 따라 들어간다**(`ROOT` 앞으로 10cm). 팔만 나가는 타격은 무게가 없다.
    🔑 반대 팔이 반대로 간다 — 대측 반동이 없으면 몸이 축을 잃는다."""
    u = (t % 0.9) / 0.9
    if u < ATTACK_WIND:                                   # 예비 — 뒤로 뺀다
        k = -0.42 * math.sin(math.pi * u / ATTACK_WIND)
    else:                                                 # 친다 → 되돌아온다
        v = (u - ATTACK_WIND) / (1 - ATTACK_WIND)
        hit = 0.42
        k = (v / hit) ** 2.1 if v < hit else 1 - _ease((v - hit) / (1 - hit))
    return {ROOT: (0.10 * k, -0.012 * abs(k), 0.0),
            # 🔑 **뺄 때 눌리고(움츠려 모으고) 뻗을 때 늘어난다.** 주먹이 몸보다 멀리
            #    나가는 느낌이 여기서 나온다 — 예비 동작이 몸을 감는 것이 곧 힘의 크기다.
            SQUASH: (-0.09 * max(k, 0.0) + 0.16 * max(-k, 0.0), 0.0, 0.0),
            # 🔑 **-96° 가 가장 앞으로 뻗는 자리다**(실측: 손 x -0.249 · z 0.600 = 어깨 높이).
            #    더 올리면 위로 가고 더 내리면 짧아진다. 주먹이 나가는 각은 이것 하나다.
            # 🔑 팔꿈치는 뺄 때 접히고(-72°) 칠 때 **완전히 펴진다**(-8°). 그 폄이 「친다」다 —
            #    친 순간에도 접혀 있으면 타격이 아니라 가드 자세로 읽힌다(첫 판이 그랬다).
            'upperarm.R': (R(-96) * k, 0, R(-4) - R(6) * _arc(abs(k))),
            'forearm.R': (R(-8) - R(64) * (1 - max(k, 0.0)), 0, 0),
            'hand.R': (R(-12) * k, 0, 0),
            'upperarm.L': (R(40) * k, 0, R(14)),          # 반대 팔이 뒤로 — 대측 반동
            'forearm.L': (R(-70) + R(20) * k, 0, 0), 'hand.L': (R(-12), 0, 0),
            'spine': (R(-8) * k, R(-16) * k, 0),          # 허리가 돌아 나간다(비틀림 Y)
            'neck': (R(-3) * k, R(5) * k, 0), 'head': (R(-2) * k, R(4) * k, 0),
            'thigh.L': (R(-14) * k, 0, 0), 'thigh.R': (R(9) * k, 0, 0),
            'shin.L': (R(10) * max(k, 0.0), 0, 0)}


