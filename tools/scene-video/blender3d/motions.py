def _ease(u):
    u = max(0.0, min(1.0, u))
    return u * u * (3 - 2 * u)


def _snap(u, p=SNAP_P):
    """빠릿빠릿 — **앞이 빠르고 뒤가 눌어붙는다.** `_ease` 는 대칭이라 시작이 굼뜨고,
    그 굼뜬 시작이 여섯 명에게 동시에 걸리면 통째로 기계로 읽힌다."""
    u = max(0.0, min(1.0, u))
    return 1 - (1 - u) ** p


def _snappy(u, dip=DIP, over=OVER, antic=ANTIC, settle=SETTLE):
    """한 번뿐인 동작의 진행값. **예비 → 빠른 본동작 → 관성 오버슛 → 정착.**

    · u < antic : **음수** — 반대로 물러나는 예비 동작(Anticipation)
    · 본동작    : `_snap` 이라 앞이 빠르다(Snappy)
    · 끝        : 1 을 `over` 만큼 지나쳤다 감쇠해 1 로 앉는다(Follow-through)

    🔴 u ≤ 0 이면 **정확히 0**, u ≥ 1 이면 **정확히 1** 이다. 이 성질이 깨지면
       `freeze`(= `reach` 의 정착 포즈)가 흔들려 아웃트로의 「굳었다」가 안 선다."""
    if u <= 0.0:
        return 0.0
    if u >= 1.0:
        return 1.0
    if u < antic:
        return -dip * math.sin(math.pi * u / antic)
    end = 1.0 - settle
    if u < end:
        return (1.0 + over) * _snap((u - antic) / (end - antic))
    return 1.0 + over * (1.0 - _ease((u - end) / settle))


def _arc(u):
    """궤적을 평면 밖으로 부풀린다(Arc). 한 평면 안 직선으로 가는 관절이 기계로 읽힌다."""
    return math.sin(math.pi * max(0.0, min(1.0, u)))


