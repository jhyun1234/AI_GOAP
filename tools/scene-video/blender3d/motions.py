LAG_C_TIP = PH_TIP / (2 * math.pi)


def _beat(u, rise=RISE, p=SNAP_P):
    """주기 동작의 진행값 0→1→0. **가는 쪽이 빠르고 오는 쪽이 눌어붙는다.**

    🔴 `sin` 은 등속이라 강약이 없다 — 일하는 동작을 사인으로 적으면 아무리 크게 흔들어도
       「기계가 왕복한다」로 읽힌다. 실측: 사인으로 적은 farm·draw·walk 의
       최대각속/평균각속이 1.2~1.4 였고, `_snap` 을 쓴 chop·eat 은 2.6~3.3 이었다.
       사람이 「역동적이지 않다」고 한 것이 정확히 앞쪽 무리다.
    🔴 u=0 과 u=1 에서 **둘 다 정확히 0** 이라야 주기가 이어진다(검사가 본다)."""
    u = u % 1.0
    if u < rise:
        return _snap(u / rise, p)
    return 1.0 - _snap((u - rise) / (1.0 - rise), p * 0.55)


def _wave(u, lag=0.0, rise=RISE, p=SNAP_P):
    """`_beat` 를 -1~1 왕복으로. 사인을 쓰던 자리를 그대로 대신한다(진폭은 안 바뀐다)."""
    return 2.0 * _beat(u - lag, rise, p) - 1.0


